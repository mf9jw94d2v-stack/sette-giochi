/**
 * Bundle src/backend (and the seven game engines it replays) into ONE plain
 * ES module for the Supabase Edge Functions:
 *
 *   supabase/functions/_shared/backend.js
 *
 * The functions run in Deno, which cannot resolve this project's `@/` alias
 * or its TypeScript paths. Bundling keeps a single source of truth: the very
 * code the tests cover is the code that runs on the server.
 *
 *   node scripts/functions/build.mjs           write the bundle
 *   node scripts/functions/build.mjs --check   fail if the committed bundle
 *                                              is not what the source builds
 */
import { build } from "vite";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const target = join(root, "supabase/functions/_shared/backend.js");
const check = process.argv.includes("--check");

const outDir = mkdtempSync(join(tmpdir(), "sgp-functions-"));
try {
  await build({
    configFile: false,
    root,
    logLevel: "warn",
    resolve: { alias: { "@": join(root, "src") } },
    define: {
      "import.meta.env.DEV": "false",
      "import.meta.env.VITE_DAILY_TIMEZONE": JSON.stringify("UTC"),
    },
    build: {
      outDir,
      emptyOutDir: true,
      minify: false,
      sourcemap: false,
      target: "es2022",
      reportCompressedSize: false,
      lib: {
        entry: join(root, "src/backend/index.ts"),
        formats: ["es"],
        fileName: () => "backend.js",
      },
    },
  });

  const header =
    "// GENERATED by scripts/functions/build.mjs from src/backend — do not edit.\n" +
    "// Rebuild with `npm run functions:build`.\n";
  const bundle = header + readFileSync(join(outDir, "backend.js"), "utf8");

  if (check) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      /* missing counts as different */
    }
    if (current !== bundle) {
      console.error(
        "supabase/functions/_shared/backend.js is out of date. Run `npm run functions:build`.",
      );
      process.exit(1);
    }
    console.log("Edge Function bundle is up to date.");
  } else {
    writeFileSync(target, bundle);
    console.log(`Wrote ${target} (${(bundle.length / 1024).toFixed(1)} kB)`);
  }
} finally {
  rmSync(outDir, { recursive: true, force: true });
}
